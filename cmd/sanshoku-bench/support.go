package main

import (
	"flag"
	"fmt"
	"io"
	"strings"
	"text/tabwriter"

	"github.com/ushineko/sanshoku/all"
	"github.com/ushineko/sanshoku/support"
)

// supportTable prints all.Support(), as a table or as docs/devices.md.
func supportTable(args []string, out, errOut io.Writer) int {
	fs := flag.NewFlagSet("support", flag.ContinueOnError)
	fs.SetOutput(errOut)
	markdown := fs.Bool("markdown", false, "print docs/devices.md")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	entries := all.Support()
	if *markdown {
		write(out, devicesPage(entries))
		return 0
	}
	tw := tabwriter.NewWriter(out, 0, 0, 2, ' ', 0)
	writeln(tw, "TIER\tDRIVER\tDEVICE\tMATCH\tCAPABILITIES\tHARDWARE\tTESTED\tSPEC")
	for _, e := range entries {
		writef(tw, "%s\t%s\t%s\t%s\t%s\t%s\t%s\t%03d\n", e.Tier, e.Driver, e.Device, e.Match,
			strings.Join(e.Capabilities, ", "), orDash(e.Hardware), testedDate(e), e.Spec)
	}
	_ = tw.Flush()
	return 0
}

const pageHead = `# Supported devices

<!-- Generated by ` + "`make generate`" + ` from all.Support(). Do not edit; edit the
     driver's Support() and regenerate. ` + "`make check-support`" + ` fails on a
     diff. -->

Three tiers. **Tested**: the bench has run against the named hardware and
the spec records the output. **Expected**: the protocol is generic and the
code path exists, but no device has confirmed it; run ` + "`sanshoku-bench read\n--driver <name>`" + ` on yours and open an issue with the ` + "`--json`" + ` output, and
the entry is promoted. **Listed**: recognised by ID, not implemented;
` + "`Open`" + ` returns ` + "`ErrUnsupported`" + `.
`

// outOfScope is the page's closing section. It is prose about what the
// module deliberately does not drive, so it lives here and not in an Entry.
const outOfScope = `## Out of scope

Every lit device (OpenRGB, the standing exception), NVIDIA temperature
(nvidia-smi; NVML is a vendor library), fan and pump duty writes on the
Kraken (the firmware discards them).

Candidates for a later spec, by the rule that direct access is preferred
wherever reasonable: SteelSeries Arctis Nova Pro battery (today via
` + "`headsetcontrol`" + `; it sits on the 0xFFC0 usage page the ` + "`steelseries`" + ` driver
already scans), and the SteelSeries legacy 0xAA protocol once a Rival is on
the desk.
`

// devicesPage renders docs/devices.md: three tier tables and the out-of-scope
// section.
func devicesPage(entries []support.Entry) string {
	var b strings.Builder
	b.WriteString(pageHead)

	section(&b, "Tested", entries, support.Tested,
		[]string{"Driver", "Device", "Match", "Capabilities", "Hardware", "Firmware", "Tested", "Spec"},
		func(e support.Entry) []string {
			return []string{e.Driver, e.Device, e.Match, caps(e), orDash(e.Hardware), orDash(e.Firmware), testedDate(e), spec(e)}
		})
	section(&b, "Expected", entries, support.Expected,
		[]string{"Driver", "Device", "Match", "Capabilities", "Notes", "Spec"},
		func(e support.Entry) []string {
			return []string{e.Driver, e.Device, e.Match, caps(e), orDash(e.Notes), spec(e)}
		})
	section(&b, "Listed", entries, support.Listed,
		[]string{"Driver", "Device", "Match", "Why", "Spec"},
		func(e support.Entry) []string {
			return []string{e.Driver, e.Device, e.Match, orDash(e.Notes), spec(e)}
		})

	b.WriteString("\n")
	b.WriteString(outOfScope)
	return b.String()
}

// section writes one tier's heading and table, or a line saying it is empty.
func section(b *strings.Builder, title string, entries []support.Entry, tier support.Tier,
	head []string, row func(support.Entry) []string) {
	writef(b, "\n## %s\n\n", title)
	var rows [][]string
	for _, e := range entries {
		if e.Tier == tier {
			rows = append(rows, row(e))
		}
	}
	if len(rows) == 0 {
		b.WriteString("None yet.\n")
		return
	}
	writeRow(b, head)
	b.WriteString(strings.Repeat("|---", len(head)) + "|\n")
	for _, r := range rows {
		writeRow(b, r)
	}
}

func writeRow(b *strings.Builder, cells []string) {
	escaped := make([]string, len(cells))
	for i, c := range cells {
		escaped[i] = strings.ReplaceAll(c, "|", `\|`)
	}
	b.WriteString("| " + strings.Join(escaped, " | ") + " |\n")
}

func caps(e support.Entry) string { return strings.Join(e.Capabilities, ", ") }
func spec(e support.Entry) string { return fmt.Sprintf("%03d", e.Spec) }

func testedDate(e support.Entry) string {
	if e.Tested.IsZero() {
		return "–"
	}
	return e.Tested.Format("2006-01-02")
}

func orDash(s string) string {
	if s == "" {
		return "–"
	}
	return s
}
